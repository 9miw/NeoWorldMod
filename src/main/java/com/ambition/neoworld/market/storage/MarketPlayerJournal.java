package com.ambition.neoworld.market.storage;

import com.ambition.neoworld.Config;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/** Business rows and after-image commit together; acknowledgement follows a verified player save. */
public final class MarketPlayerJournal {
    public interface PlayerState {
        byte[] capture() throws Exception;
        void restore(byte[] state) throws Exception;
        boolean hasCheckpoint(UUID operation) throws Exception;
        void save(UUID operation) throws Exception;
    }
    public record Result(String code, long listingId) {}
    public record Entry(UUID operation, UUID player, String world, String type, byte[] state, Result result, boolean applied) {}
    @FunctionalInterface public interface Action { Result run(Connection c) throws Exception; }
    private final MarketSql.Connections connections;
    private final String table;
    private final String world;

    public MarketPlayerJournal(MarketSql.Connections connections, String table) {
        this(connections, table, "");
    }

    public MarketPlayerJournal(MarketSql.Connections connections, String table, String world) {
        if (!table.matches("[a-zA-Z_][a-zA-Z0-9_]*")) throw new IllegalArgumentException("Invalid journal table");
        this.connections = connections; this.table = table; this.world = world;
    }

    public static void createSchema(Connection c, Config.DatabaseType type, String prefix) throws SQLException {
        String blob = type == Config.DatabaseType.H2 ? "BINARY LARGE OBJECT" : "LONGBLOB";
        String sequence = type == Config.DatabaseType.H2 ? "BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE" : "BIGINT AUTO_INCREMENT UNIQUE";
        try (var s = c.createStatement()) {
            s.executeUpdate("CREATE TABLE IF NOT EXISTS " + prefix + "market_player_journal ("
                    + "operation_id VARCHAR(36) PRIMARY KEY, player_id VARCHAR(36) NOT NULL,"
                    + "journal_seq " + sequence + ", world_id VARCHAR(36) NOT NULL DEFAULT '',"
                    + "operation_type VARCHAR(32) NOT NULL, player_state " + blob + " NOT NULL,"
                    + "result_code VARCHAR(32) NOT NULL, listing_id BIGINT NOT NULL,"
                    + "applied BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
            s.executeUpdate("CREATE INDEX IF NOT EXISTS " + prefix + "idx_market_journal_player ON "
                    + prefix + "market_player_journal (player_id,world_id,applied)");
        }
    }

    public Result execute(UUID operation, UUID owner, String type, PlayerState player, Action action) throws Exception {
        recover(owner, player);
        Entry existing = find(operation);
        if (existing != null) {
            if (!existing.player().equals(owner) || !existing.type().equals(type) || !existing.world().equals(world))
                throw new SQLException("Market operation owner/type mismatch");
            return existing.result();
        }
        byte[] before = player.capture();
        Result result;
        try {
            result = MarketSql.atomic(connections, c -> {
                Result outcome = action.run(c);
                if (!outcome.code().equals("SUCCESS")) throw new Rejected(outcome);
                try (var s = c.prepareStatement("INSERT INTO " + table
                        + " (operation_id,player_id,operation_type,player_state,result_code,listing_id,world_id) VALUES (?,?,?,?,?,?,?)")) {
                    s.setString(1, operation.toString()); s.setString(2, owner.toString()); s.setString(3, type);
                    s.setBytes(4, player.capture()); s.setString(5, outcome.code()); s.setLong(6, outcome.listingId());
                    s.setString(7, world);
                    s.executeUpdate();
                }
                return outcome;
            });
        } catch (Exception failure) {
            // Never let disconnect persist an uncheckpointed partial mutation when SQL is unavailable.
            // If commit actually succeeded, its after-image will replay on recovery.
            player.restore(before);
            Entry committed = find(operation);
            if (committed != null) {
                recover(owner, player);
                return committed.result();
            }
            Throwable cause = failure;
            while (cause != null) {
                if (cause instanceof Rejected rejected) return rejected.result;
                cause = cause.getCause();
            }
            throw failure;
        }
        player.save(operation);
        acknowledge(operation, owner);
        return result;
    }

    public void recover(UUID owner, PlayerState player) throws Exception {
        List<Entry> pending = new ArrayList<>();
        try (var c = connections.open(); var s = c.prepareStatement("SELECT * FROM " + table
                + " WHERE player_id=? AND world_id=? AND applied=FALSE ORDER BY journal_seq")) {
            s.setString(1, owner.toString());
            s.setString(2, world);
            try (var r = s.executeQuery()) { while (r.next()) pending.add(read(r)); }
        }
        if (pending.size() > 1) throw new SQLException("Multiple pending player snapshots require review");
        for (Entry entry : pending) {
            if (!player.hasCheckpoint(entry.operation())) {
                player.restore(entry.state());
                player.save(entry.operation());
            }
            acknowledge(entry.operation(), owner);
        }
    }

    /** Singleplayer owner can load an older checkpoint from level.dat despite a newer playerdata save. */
    public void recoverOwner(UUID owner, PlayerState player) throws Exception {
        recover(owner, player);
        Entry latest;
        try (var c = connections.open(); var s = c.prepareStatement("SELECT * FROM " + table
                + " WHERE player_id=? AND world_id=? ORDER BY journal_seq DESC LIMIT 1")) {
            s.setString(1, owner.toString()); s.setString(2, world);
            try (var r = s.executeQuery()) { latest = r.next() ? read(r) : null; }
        }
        if (latest != null && !player.hasCheckpoint(latest.operation())) {
            player.restore(latest.state());
            player.save(latest.operation());
        }
    }

    public Entry find(UUID operation) throws SQLException {
        try (var c = connections.open(); var s = c.prepareStatement("SELECT * FROM " + table + " WHERE operation_id=?")) {
            s.setString(1, operation.toString());
            try (var r = s.executeQuery()) { return r.next() ? read(r) : null; }
        }
    }

    private Entry read(java.sql.ResultSet r) throws SQLException {
        return new Entry(UUID.fromString(r.getString("operation_id")), UUID.fromString(r.getString("player_id")), r.getString("world_id"),
                r.getString("operation_type"), r.getBytes("player_state"),
                new Result(r.getString("result_code"), r.getLong("listing_id")), r.getBoolean("applied"));
    }

    private void acknowledge(UUID operation, UUID player) throws SQLException {
        try (var c = connections.open()) {
            c.setAutoCommit(false);
            try {
                try (var s = c.prepareStatement("UPDATE " + table
                        + " SET applied=TRUE WHERE operation_id=? AND player_id=? AND world_id=?")) {
                    s.setString(1, operation.toString()); s.setString(2, player.toString()); s.setString(3, world);
                    if (s.executeUpdate() != 1) throw new SQLException("Missing market checkpoint journal");
                }
                compactApplied(c, player);
                c.commit();
            } catch (SQLException failure) {
                try { c.rollback(); } catch (SQLException rollback) { failure.addSuppressed(rollback); }
                throw failure;
            }
        }
    }

    /** Keep the latest applied after-image and all pending after-images; retain every operation receipt. */
    public int compactApplied(UUID owner) throws SQLException {
        try (var c = connections.open()) {
            c.setAutoCommit(false);
            try {
                int changed=compactApplied(c,owner); c.commit(); return changed;
            } catch(SQLException failure) {
                try { c.rollback(); } catch(SQLException rollback) { failure.addSuppressed(rollback); }
                throw failure;
            }
        }
    }

    private int compactApplied(Connection c, UUID owner) throws SQLException {
        long latest;
        try (var s=c.prepareStatement("SELECT journal_seq,OCTET_LENGTH(player_state) FROM "+table
                +" WHERE player_id=? AND world_id=? AND applied=TRUE ORDER BY journal_seq DESC LIMIT 1")) {
            s.setString(1,owner.toString()); s.setString(2,world);
            try(var r=s.executeQuery()) {
                if(!r.next()) return 0;
                latest=r.getLong(1);
                if(r.getLong(2)==0) throw new SQLException("Latest applied player checkpoint has no snapshot");
            }
        }
        try(var s=c.prepareStatement("UPDATE "+table+" SET player_state=? WHERE player_id=? AND world_id=?"
                +" AND applied=TRUE AND journal_seq<? AND OCTET_LENGTH(player_state)>0")) {
            s.setBytes(1,new byte[0]); s.setString(2,owner.toString()); s.setString(3,world); s.setLong(4,latest);
            return s.executeUpdate();
        }
    }

    public record CompactionBatch(int groups, int snapshots) {}

    /** Bounded historical backfill, including inactive players/worlds. Run off the server thread. */
    public static CompactionBatch compactBatch(MarketSql.Connections connections, String table, int limit) throws SQLException {
        if(!table.matches("[a-zA-Z_][a-zA-Z0-9_]*") || limit<1 || limit>1024)
            throw new IllegalArgumentException("Invalid journal compaction batch");
        record Group(UUID player,String world) {}
        List<Group> groups=new ArrayList<>();
        try(var c=connections.open();var s=c.prepareStatement("SELECT player_id,world_id FROM "+table
                +" WHERE applied=TRUE AND OCTET_LENGTH(player_state)>0 GROUP BY player_id,world_id"
                +" HAVING COUNT(*)>1 ORDER BY player_id,world_id LIMIT ?")) {
            s.setInt(1,limit);
            try(var r=s.executeQuery()) {
                while(r.next()) groups.add(new Group(UUID.fromString(r.getString(1)),r.getString(2)));
            }
        }
        int changed=0;
        for(var group:groups) changed+=new MarketPlayerJournal(connections,table,group.world()).compactApplied(group.player());
        return new CompactionBatch(groups.size(),changed);
    }

    private static final class Rejected extends Exception {
        final Result result;
        Rejected(Result result) { this.result = result; }
    }
}
