package com.ambition.neoworld.shop;

import com.ambition.neoworld.Config;
import com.ambition.neoworld.database.NeoWorldDatabase;
import com.ambition.neoworld.market.storage.MarketItemCodec;
import net.minecraft.core.HolderLookup;
import net.minecraft.world.item.ItemStack;
import java.io.IOException;
import java.sql.*;
import java.util.*;

/** Catalog and audit trail share the existing NeoWorld database. */
public final class ShopRepository {
    public enum TransactionStatus { PENDING, COMMITTED, ROLLED_BACK, FAILED, NEEDS_REVIEW }
    public record Shop(long id, String name) {}
    public record Offer(long id, long shopId, ItemStack item, long buy, long sell, String category, ShopCurrency currency) {}
    public record ShopTransaction(
            String id, UUID playerId, long shopId, long offerId, String action,
            int quantity, long totalAmount, ShopCurrency currency, TransactionStatus status,
            long txSeq, long balanceBefore, long balanceAfter, Timestamp createdAt
    ) {}

    private ShopRepository() {}
    private static String table(String name) { return NeoWorldDatabase.tableName("shop_" + name); }

    public static void createSchema(Connection c, Config.DatabaseType type, String prefix) throws SQLException {
        String identity = type == Config.DatabaseType.H2 ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "BIGINT AUTO_INCREMENT PRIMARY KEY";
        String blob = type == Config.DatabaseType.H2 ? "BINARY LARGE OBJECT" : "LONGBLOB";
        try (Statement s = c.createStatement()) {
            s.executeUpdate("CREATE TABLE IF NOT EXISTS " + prefix + "shop_stores (id " + identity + ", name VARCHAR(64) NOT NULL)");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS " + prefix + "shop_offers (id " + identity
                    + ", shop_id BIGINT NOT NULL, item_nbt " + blob + " NOT NULL, buy_price BIGINT NOT NULL, sell_price BIGINT NOT NULL, category VARCHAR(32) NOT NULL, FOREIGN KEY (shop_id) REFERENCES " + prefix + "shop_stores(id))");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS " + prefix + "shop_transactions (id VARCHAR(36) PRIMARY KEY, player_id VARCHAR(36) NOT NULL, shop_id BIGINT NOT NULL, offer_id BIGINT NOT NULL, action VARCHAR(4) NOT NULL, quantity INTEGER NOT NULL, total_silver BIGINT NOT NULL, item_nbt " + blob + " NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        }
    }

    public static Shop create(String name) throws SQLException {
        if (name == null || name.isBlank() || name.length() > 64) throw new IllegalArgumentException("ชื่อร้านต้องยาว 1–64 ตัวอักษร");
        return com.ambition.neoworld.market.storage.MarketSql.transaction(c -> {
            try (PreparedStatement s = c.prepareStatement("INSERT INTO " + table("stores") + " (name) VALUES (?)", Statement.RETURN_GENERATED_KEYS)) {
                s.setString(1, name.strip()); s.executeUpdate();
                try (ResultSet r = s.getGeneratedKeys()) {
                    if (!r.next()) throw new SQLException("Missing generated shop ID");
                    return new Shop(r.getLong(1), name.strip());
                }
            }
        });
    }

    public static void rename(long id, String name) throws SQLException {
        if (name == null || name.isBlank() || name.length() > 64)
            throw new IllegalArgumentException("ชื่อร้านต้องยาว 1–64 ตัวอักษร");
        int updated = com.ambition.neoworld.market.storage.MarketSql.transaction(c -> {
            try (PreparedStatement s = c.prepareStatement("UPDATE " + table("stores") + " SET name=? WHERE id=?")) {
                s.setString(1, name.strip());
                s.setLong(2, id);
                return s.executeUpdate();
            }
        });
        // MariaDB may report zero changed rows when the name already matches.
        if (updated == 0 && shop(id) == null) throw new IllegalArgumentException("ไม่พบร้านค้า ID " + id);
    }

    /** Version 9: rerunnable even when a database implicitly commits individual DDL statements. */
    public static void addCurrencies(Connection c, String prefix) throws SQLException {
        try (Statement s = c.createStatement()) {
            s.executeUpdate("ALTER TABLE " + prefix + "shop_offers ADD COLUMN IF NOT EXISTS currency VARCHAR(16) NOT NULL DEFAULT 'SILVER'");
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS currency VARCHAR(16) NOT NULL DEFAULT 'SILVER'");
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS total_amount BIGINT NOT NULL DEFAULT -1");
            // Preserve old Silver history; a retry must not overwrite completed Gold/Diamond records.
            s.executeUpdate("UPDATE " + prefix + "shop_transactions SET total_amount=total_silver WHERE total_amount=-1");
        }
    }

    /** Version 13: crash-recovery schema, monotonic sequence per player, and performance indexes. */
    public static void addRecoverySchema(Connection c, Config.DatabaseType type, String prefix) throws SQLException {
        try (Statement s = c.createStatement()) {
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'COMMITTED'");
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS tx_seq BIGINT NOT NULL DEFAULT 0");
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS balance_before BIGINT NOT NULL DEFAULT -1");
            s.executeUpdate("ALTER TABLE " + prefix + "shop_transactions ADD COLUMN IF NOT EXISTS balance_after BIGINT NOT NULL DEFAULT -1");
            s.executeUpdate("CREATE INDEX IF NOT EXISTS " + prefix + "idx_shop_tx_player_status ON " + prefix + "shop_transactions (player_id, status)");
            s.executeUpdate("CREATE INDEX IF NOT EXISTS " + prefix + "idx_shop_offers_shop_offer ON " + prefix + "shop_offers (shop_id, id)");
        }
    }

    public static List<Shop> shops() throws SQLException {
        try (Connection c = com.ambition.neoworld.market.storage.MarketSql.connection(); Statement s = c.createStatement();
             ResultSet r = s.executeQuery("SELECT id, name FROM " + table("stores") + " ORDER BY id")) {
            List<Shop> result = new ArrayList<>();
            while (r.next()) result.add(new Shop(r.getLong(1), r.getString(2)));
            return result;
        }
    }

    public static Shop shop(long id) throws SQLException {
        try (Connection c = com.ambition.neoworld.market.storage.MarketSql.connection(); PreparedStatement s = c.prepareStatement("SELECT name FROM " + table("stores") + " WHERE id=?")) {
            s.setLong(1, id);
            try (ResultSet r = s.executeQuery()) { return r.next() ? new Shop(id, r.getString(1)) : null; }
        }
    }

    public static List<Offer> offers(long shop, HolderLookup.Provider registries) throws SQLException, IOException {
        try (Connection c = com.ambition.neoworld.market.storage.MarketSql.connection(); PreparedStatement s = c.prepareStatement("SELECT id, item_nbt, buy_price, sell_price, category, currency FROM " + table("offers") + " WHERE shop_id=? ORDER BY category, id")) {
            s.setLong(1, shop);
            try (ResultSet r = s.executeQuery()) {
                List<Offer> result = new ArrayList<>();
                while (r.next()) result.add(new Offer(r.getLong(1), shop, MarketItemCodec.decode(r.getBytes(2), registries), r.getLong(3), r.getLong(4), r.getString(5), ShopCurrency.valueOf(r.getString(6))));
                return result;
            }
        }
    }

    public static Offer offer(long shop, long offerId, HolderLookup.Provider registries) throws SQLException, IOException {
        return offer(shop, offerId, registries, false);
    }

    public static Offer lockedOffer(long shop, long offerId, HolderLookup.Provider registries) throws SQLException, IOException {
        return offer(shop, offerId, registries, true);
    }

    private static Offer offer(long shop, long offerId, HolderLookup.Provider registries, boolean lock) throws SQLException, IOException {
        try (Connection c = com.ambition.neoworld.market.storage.MarketSql.connection(); PreparedStatement s = c.prepareStatement("SELECT id, item_nbt, buy_price, sell_price, category, currency FROM " + table("offers") + " WHERE shop_id=? AND id=?" + (lock ? " FOR UPDATE" : ""))) {
            s.setLong(1, shop);
            s.setLong(2, offerId);
            try (ResultSet r = s.executeQuery()) {
                if (!r.next()) return null;
                return new Offer(r.getLong(1), shop, MarketItemCodec.decode(r.getBytes(2), registries), r.getLong(3), r.getLong(4), r.getString(5), ShopCurrency.valueOf(r.getString(6)));
            }
        }
    }

    public static long add(long shop, ItemStack item, long buy, long sell, String category, ShopCurrency currency, HolderLookup.Provider registries) throws SQLException, IOException {
        Objects.requireNonNull(currency, "Shop currency");
        if (shop(shop) == null) throw new IllegalArgumentException("ไม่พบร้านค้า");
        if (item.isEmpty() || !ShopRules.validPrices(buy, sell) || category.isBlank() || category.length() > 32)
            throw new IllegalArgumentException("ราคาไม่ถูกต้อง: ใช้ 0 เพื่อปิดซื้อ/ขาย และราคาขายคืนต้องต่ำกว่าราคาซื้อ");
        ItemStack unit = item.copyWithCount(1);
        // Check identical component-bearing stacks across every shop to prevent arbitrage.
        for (Shop store : shops()) for (Offer offer : offers(store.id(), registries)) {
            if (ItemStack.isSameItemSameComponents(unit, offer.item())
                    && ShopRules.conflicts(buy, sell, currency, offer.buy(), offer.sell(), offer.currency()))
                throw new IllegalArgumentException("ราคานี้ทำให้ซื้อ–ขายวนกำไรระหว่างร้านได้");
        }
        byte[] bytes = MarketItemCodec.encode(unit, registries);
        return com.ambition.neoworld.market.storage.MarketSql.transaction(c -> {
            try (PreparedStatement s = c.prepareStatement("INSERT INTO " + table("offers") + " (shop_id,item_nbt,buy_price,sell_price,category,currency) VALUES (?,?,?,?,?,?)", Statement.RETURN_GENERATED_KEYS)) {
                s.setLong(1, shop); s.setBytes(2, bytes); s.setLong(3, buy); s.setLong(4, sell); s.setString(5, category); s.setString(6,currency.name()); s.executeUpdate();
                try (ResultSet r = s.getGeneratedKeys()) {
                    if (!r.next()) throw new SQLException("Missing offer ID");
                    long id = r.getLong(1);
                    var history = com.ambition.neoworld.economy.analytics.AnalyticsHistory.item(unit, registries);
                    history.addProperty("buy", buy); history.addProperty("sell", sell); history.addProperty("currency", currency.name());
                    com.ambition.neoworld.economy.analytics.AnalyticsHistory.config(c, "shop_offer_added", shop + "/" + id, history);
                    return id;
                }
            }
        });
    }

    public static boolean remove(long shop, long offer) throws SQLException {
        return com.ambition.neoworld.market.storage.MarketSql.transaction(c -> {
            try (PreparedStatement before = c.prepareStatement("SELECT item_nbt,buy_price,sell_price,currency FROM " + table("offers") + " WHERE shop_id=? AND id=? FOR UPDATE")) {
                before.setLong(1,shop); before.setLong(2,offer);
                try (ResultSet r=before.executeQuery()) {
                    if(!r.next())return false;
                    var history=new com.google.gson.JsonObject();
                    history.addProperty("item_nbt_base64", java.util.Base64.getEncoder().encodeToString(r.getBytes(1)));
                    history.addProperty("buy",r.getLong(2)); history.addProperty("sell",r.getLong(3)); history.addProperty("currency",r.getString(4));
                    com.ambition.neoworld.economy.analytics.AnalyticsHistory.config(c,"shop_offer_removed",shop + "/" + offer,history);
                }
            }
            try (PreparedStatement s = c.prepareStatement("DELETE FROM " + table("offers") + " WHERE shop_id=? AND id=?")) {
                s.setLong(1, shop); s.setLong(2, offer); return s.executeUpdate() == 1;
            }
        });
    }

    public static void recordPending(Connection c, String txId, UUID player, Offer offer, boolean sell, int quantity, long total, long txSeq, long balanceBefore, long balanceAfter, HolderLookup.Provider registries) throws SQLException, IOException {
        try (PreparedStatement s = c.prepareStatement(
                "INSERT INTO " + table("transactions")
                        + " (id,player_id,shop_id,offer_id,action,quantity,total_silver,item_nbt,currency,total_amount,status,tx_seq,balance_before,balance_after) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)")) {
            s.setString(1, txId);
            s.setString(2, player.toString());
            s.setLong(3, offer.shopId());
            s.setLong(4, offer.id());
            s.setString(5, sell ? "SELL" : "BUY");
            s.setInt(6, quantity);
            s.setLong(7, offer.currency() == ShopCurrency.SILVER ? total : 0);
            s.setBytes(8, MarketItemCodec.encode(offer.item(), registries));
            s.setString(9, offer.currency().name());
            s.setLong(10, total);
            s.setString(11, TransactionStatus.PENDING.name());
            s.setLong(12, txSeq);
            s.setLong(13, balanceBefore);
            s.setLong(14, balanceAfter);
            s.executeUpdate();
        }
    }

    public static boolean updateTransactionStatus(Connection c, String txId, TransactionStatus status) throws SQLException {
        return updateTransactionStatus(c, table("transactions"), txId, status);
    }

    /** Caller owns the shared journal transaction; item bytes retain the complete ItemStack codec payload. */
    public static void recordCommitted(Connection c, UUID operation, UUID player, long shop, long offer,
            boolean sell, int quantity, long total, ShopCurrency currency, byte[] itemData,
            long before, long after) throws SQLException {
        try (var s = c.prepareStatement("INSERT INTO " + table("transactions")
                + " (id,player_id,shop_id,offer_id,action,quantity,total_silver,item_nbt,currency,total_amount,status,tx_seq,balance_before,balance_after)"
                + " VALUES (?,?,?,?,?,?,?,?,?,?,'COMMITTED',0,?,?)")) {
            s.setString(1, operation.toString()); s.setString(2, player.toString());
            s.setLong(3, shop); s.setLong(4, offer); s.setString(5, sell ? "SELL" : "BUY"); s.setInt(6, quantity);
            s.setLong(7, currency == ShopCurrency.SILVER ? total : 0); s.setBytes(8, itemData);
            s.setString(9, currency.name()); s.setLong(10, total); s.setLong(11, before); s.setLong(12, after);
            s.executeUpdate();
        }
    }

    public static int markLegacyPendingForReview(Connection c, UUID player) throws SQLException {
        return markLegacyPendingForReview(c, table("transactions"), player);
    }

    public static int markLegacyPendingForReview(Connection c, String tableName, UUID player) throws SQLException {
        try (var s = c.prepareStatement("UPDATE " + tableName + " SET status='NEEDS_REVIEW' WHERE player_id=? AND status='PENDING'")) {
            s.setString(1, player.toString());
            return s.executeUpdate();
        }
    }

    public static boolean updateTransactionStatus(Connection c, String tableName, String txId, TransactionStatus status) throws SQLException {
        try (PreparedStatement s = c.prepareStatement("UPDATE " + tableName + " SET status=? WHERE id=?")) {
            s.setString(1, status.name());
            s.setString(2, txId);
            return s.executeUpdate() > 0;
        }
    }

    public static List<ShopTransaction> pendingTransactions(Connection c, UUID player) throws SQLException {
        return pendingTransactions(c, table("transactions"), player);
    }

    public static List<ShopTransaction> pendingTransactions(Connection c, String tableName, UUID player) throws SQLException {
        try (PreparedStatement s = c.prepareStatement(
                "SELECT id, player_id, shop_id, offer_id, action, quantity, total_amount, currency, status, tx_seq, balance_before, balance_after, created_at FROM "
                        + tableName + " WHERE player_id=? AND status='PENDING' ORDER BY tx_seq ASC")) {
            s.setString(1, player.toString());
            try (ResultSet r = s.executeQuery()) {
                List<ShopTransaction> result = new ArrayList<>();
                while (r.next()) {
                    result.add(new ShopTransaction(
                            r.getString(1),
                            UUID.fromString(r.getString(2)),
                            r.getLong(3),
                            r.getLong(4),
                            r.getString(5),
                            r.getInt(6),
                            r.getLong(7),
                            ShopCurrency.valueOf(r.getString(8)),
                            TransactionStatus.valueOf(r.getString(9)),
                            r.getLong(10),
                            r.getLong(11),
                            r.getLong(12),
                            r.getTimestamp(13)
                    ));
                }
                return result;
            }
        }
    }

    public static void audit(Connection c, UUID player, Offer offer, boolean sell, int quantity, long total, HolderLookup.Provider registries) throws SQLException, IOException {
        String txId = com.ambition.neoworld.economy.analytics.EconomyAnalytics.correlation(player);
        try (PreparedStatement s = c.prepareStatement("INSERT INTO " + table("transactions") + " (id,player_id,shop_id,offer_id,action,quantity,total_silver,item_nbt,currency,total_amount,status,tx_seq,balance_before,balance_after) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)")) {
            s.setString(1, txId); s.setString(2, player.toString()); s.setLong(3, offer.shopId()); s.setLong(4, offer.id());
            s.setString(5, sell ? "SELL" : "BUY"); s.setInt(6, quantity); s.setLong(7, offer.currency() == ShopCurrency.SILVER ? total : 0);
            s.setBytes(8, MarketItemCodec.encode(offer.item(), registries));
            s.setString(9,offer.currency().name()); s.setLong(10,total);
            s.setString(11, TransactionStatus.COMMITTED.name());
            s.setLong(12, 0L);
            s.setLong(13, -1L);
            s.setLong(14, -1L);
            s.executeUpdate();
        }
    }
}
